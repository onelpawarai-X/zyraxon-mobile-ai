package ai.zyraxon.assistant.world

/**
 * What the call agent says, per language. Fifteen languages are fast rule-based packs; every other
 * language (and any caller the rules cannot follow) is handled by the model, which answers in the
 * caller's own language. Words that mean goodbye / urgent / spam / "no" are checked in ALL languages at once.
 */
class LangPack(
    val code: String,
    private val lines: List<String>,
    val nameIntros: List<String>,
    val nameSuffixes: List<String> = emptyList()
) {
    private fun f(i: Int, owner: String = "", name: String = "") = lines[i].replace("{owner}", owner).replace("{name}", name)
    fun greetKnown(owner: String, name: String) = f(0, owner, name)
    fun greetUnknown(owner: String) = f(1, owner)
    fun askPurpose(name: String) = f(2, name = name)
    fun noted(owner: String, name: String) = f(3, owner, name)
    fun askNameOnce() = f(4)
    fun takeMessage() = f(5)
    fun thanksPurpose(owner: String) = f(6, owner)
    fun writtenDown() = f(7)
    fun byeNormal() = f(8)
    fun byeMessage() = f(9)
    fun tooLong() = f(10)
    fun spamClose() = f(11)
    fun areYouThere() = f(12)
    fun noLine() = f(13)
    fun fallbackAnswer() = f(14)

